# Helpers
# ============================================================
def _audit_entry(c: ChangeEntry) -> dict[str, Any]:
    return c.model_dump(mode="json")


def _merge_entity(
    existing: dict[str, Any], incoming: dict[str, Any], *, now: str
) -> dict[str, Any]:
    """Conservative deep-merge: incoming wins, but list fields merge by union
    (preserving existing order and appending new), and ``attributes``/``facets``
    nested dicts merge by key. Always bumps ``updated_at``."""
    merged = copy.deepcopy(existing)
    for key, value in incoming.items():
        if key in {"created_at"}:
            continue  # never overwrite created_at
        if key in {"labels", "aliases", "provenance"} and isinstance(value, list):
            current = merged.get(key, [])
            for v in value:
                if v not in current:
                    current.append(v)
            merged[key] = current
        elif key == "attributes" and isinstance(value, dict):
            base = merged.get("attributes", {})
            base.update(value)
            merged["attributes"] = base
        elif key == "facets" and isinstance(value, dict):
            base = merged.get("facets") or {}
            for axis, v in value.items():
                if isinstance(v, list):
                    cur = base.get(axis, [])
                    for item in v:
                        if item not in cur:
                            cur.append(item)
                    base[axis] = cur
                else:
                    base[axis] = v
            merged["facets"] = base
        else:
            merged[key] = value
    merged["updated_at"] = now
    return merged


def _merge_relation(
    existing: dict[str, Any], incoming: dict[str, Any], *, now: str
) -> dict[str, Any]:
    """Incoming wins on simple fields; ``weights`` list merges by period (new
    observations append; same period gets overwritten); ``provenance``/
    ``attributes`` follow entity merge rules."""
    merged = copy.deepcopy(existing)
    for key, value in incoming.items():
        if key in {"created_at"}:
            continue
        if key == "weights" and isinstance(value, list):
            current = merged.get("weights", [])
            by_period = {w["period"]: w for w in current}
            for w in value:
                by_period[w["period"]] = w
            merged["weights"] = list(by_period.values())
        elif key in {"provenance"} and isinstance(value, list):
            cur = merged.get(key, [])
            for v in value:
                if v not in cur:
                    cur.append(v)
            merged[key] = cur
        elif key == "attributes" and isinstance(value, dict):
            base = merged.get("attributes", {})
            base.update(value)
            merged["attributes"] = base
        else:
            merged[key] = value
    merged["updated_at"] = now
    return merged


def _shallow_diff(
    before: dict[str, Any], after: dict[str, Any]
) -> dict[str, Any]:
    """Top-level keys whose values differ. Used to report write actions."""
    diff: dict[str, Any] = {}
    keys = set(before) | set(after)
    for k in keys:
        if before.get(k) != after.get(k):
            diff[k] = {"before": before.get(k), "after": after.get(k)}
    return diff
